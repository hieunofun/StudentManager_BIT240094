const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const { createWebServer } = require('./web-server.cjs');

const key = '@StudentManager_BIT240094/students';
const port = Number(process.env.TEST_PORT || 8085);
const url = `http://127.0.0.1:${port}`;
const output = path.resolve(__dirname, '../test-results');
fs.mkdirSync(output, { recursive: true });
let checks = 0;
const passed = (message) => { checks++; console.log(`PASS ${message}`); };
const text = (page, value) => page.getByText(value, { exact: true }).filter({ visible: true });
const click = (page, value) => page.getByRole('button', { name: value, exact: true }).click();
const fill = (page, label, value) => page.getByRole('textbox', { name: label, exact: true }).fill(value);
const data = (page) => page.evaluate((storageKey) => JSON.parse(localStorage.getItem(storageKey) || '[]'), key);

async function main() {
  const server = createWebServer(port);
  await new Promise((resolve) => server.listen(port, '127.0.0.1', resolve));
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined });
  try {
    const context = await browser.newContext({ locale: 'vi-VN', viewport: { width: 375, height: 812 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(url);
    await text(page, 'Chưa có sinh viên').waitFor();
    await text(page, 'Quản lý sinh viên').waitFor();
    passed('Vietnamese language and empty list');
    await click(page, 'Thêm mới');
    assert.equal(await page.getByRole('textbox', { name: 'Họ tên', exact: true }).inputValue(), '');
    await fill(page, 'Họ tên', '   ');
    await fill(page, 'MSSV', '   ');
    await fill(page, 'Email', '   ');
    await click(page, 'Lưu');
    await text(page, 'Vui lòng nhập họ tên.').waitFor();
    await text(page, 'Vui lòng nhập email.').waitFor();
    assert.deepEqual(await data(page), []);
    passed('Empty required fields are blocked');
    await fill(page, 'Họ tên', ' Phan Văn Hiếu ');
    await fill(page, 'Email', 'invalid-email');
    for (const value of ['AIT240094', 'Bit240094', 'BIT210094', 'BIT270094', 'BIT24009']) {
      await fill(page, 'MSSV', value);
      await click(page, 'Lưu');
      await text(page, 'MSSV không hợp lệ. Ví dụ đúng: BIT240094').waitFor();
    }
    await text(page, 'Email không hợp lệ. Ví dụ đúng: hieu@example.com').waitFor();
    passed('All invalid student ID examples and malformed email are blocked');
    await fill(page, 'MSSV', ' BIT240094 ');
    await fill(page, 'Email', ' hieu@example.com ');
    await fill(page, 'Link ảnh đại diện (không bắt buộc)', 'file:///photo.png');
    await click(page, 'Lưu');
    await text(page, 'Link ảnh phải là URL http hoặc https hợp lệ.').waitFor();
    await fill(page, 'Link ảnh đại diện (không bắt buộc)', '');
    const chooser = page.waitForEvent('filechooser');
    await click(page, 'Chọn ảnh từ thiết bị');
    await (await chooser).setFiles(path.resolve(__dirname, '../assets/images/icon.png'));
    await page.getByRole('button', { name: 'Chọn ảnh từ thiết bị', exact: true }).waitFor();
    await click(page, 'Lưu');
    await text(page, 'Chi tiết sinh viên').waitFor();
    await text(page, 'Phan Văn Hiếu').waitFor();
    await text(page, 'BIT240094').waitFor();
    await text(page, 'hieu@example.com').waitFor();
    const initial = await data(page);
    assert.equal(initial.length, 1);
    assert.equal(initial[0].name, 'Phan Văn Hiếu');
    assert.match(initial[0].avatarUri, /^data:image\/png;base64,/);
    passed('Add trims data, selects a photo, and shows the correct detail');
    await page.screenshot({ path: path.join(output, 'detail-vi.png') });
    await page.reload();
    await text(page, 'Phan Văn Hiếu').waitFor();
    assert.deepEqual(await data(page), initial);
    await context.storageState({ path: path.join(output, 'storage-state.json') });
    const reopened = await browser.newContext({ locale: 'vi-VN', storageState: path.join(output, 'storage-state.json'), viewport: { width: 375, height: 812 } });
    const reopenedPage = await reopened.newPage();
    await reopenedPage.goto(url);
    await reopenedPage.getByRole('button', { name: 'Phan Văn Hiếu, BIT240094' }).waitFor();
    assert.deepEqual(await data(reopenedPage), initial);
    await reopened.close();
    passed('Reload and a new browser context retain the record and selected photo');
    await click(page, 'Sửa');
    await fill(page, 'Họ tên', 'Hiếu đã chỉnh sửa');
    await click(page, 'Lưu');
    await text(page, 'Bạn có muốn sửa thông tin SV không?').waitFor();
    await click(page, 'Không');
    assert.deepEqual(await data(page), initial);
    assert.equal(await page.getByRole('textbox', { name: 'Họ tên', exact: true }).inputValue(), 'Hiếu đã chỉnh sửa');
    const cancelChooser = page.waitForEvent('filechooser');
    await click(page, 'Chọn ảnh từ thiết bị');
    await (await cancelChooser).setFiles([]);
    await page.getByRole('button', { name: 'Chọn ảnh từ thiết bị', exact: true }).waitFor();
    assert.deepEqual(await data(page), initial);
    await click(page, 'Lưu');
    await click(page, 'Có');
    await text(page, 'Chi tiết sinh viên').waitFor();
    await text(page, 'Hiếu đã chỉnh sửa').waitFor();
    const edited = await data(page);
    assert.equal(edited[0].id, initial[0].id);
    assert.equal(edited[0].avatarUri, initial[0].avatarUri);
    passed('Edit No retains draft/old storage; photo cancel retains avatar; Edit Yes preserves stable ID');
    await click(page, 'Quay lại');
    await page.getByRole('button', { name: 'Hiếu đã chỉnh sửa, BIT240094' }).waitFor();
    await click(page, 'Thêm mới');
    await fill(page, 'Họ tên', 'Sinh viên thứ hai');
    await fill(page, 'MSSV', 'BIT240094');
    await fill(page, 'Email', 'second@example.com');
    await click(page, 'Lưu');
    await text(page, 'MSSV đã tồn tại. Vui lòng nhập MSSV khác.').waitFor();
    await fill(page, 'MSSV', 'BZZ269999');
    await page.route('https://example.com/missing-avatar.png', (route) => route.fulfill({ status: 404, body: '' }));
    await fill(page, 'Link ảnh đại diện (không bắt buộc)', 'https://example.com/missing-avatar.png');
    await page.getByRole('button', { name: 'Lưu', exact: true }).evaluate((element) => { element.click(); element.click(); });
    await text(page, 'Chi tiết sinh viên').waitFor();
    assert.equal((await data(page)).length, 2);
    await page.waitForFunction(() => [...document.querySelectorAll('[data-testid="student-avatar"] img')].some((image) => image.src.includes('default-avatar') && image.complete && image.naturalWidth > 0));
    passed('Duplicate IDs blocked, repeated Save adds once, broken URL uses default avatar');
    await click(page, 'Sửa');
    await fill(page, 'MSSV', 'BIT240094');
    await click(page, 'Lưu');
    await text(page, 'MSSV đã tồn tại. Vui lòng nhập MSSV khác.').waitFor();
    await click(page, 'Hủy');
    await text(page, 'Sinh viên thứ hai').waitFor();
    await click(page, 'Xóa');
    await text(page, 'Bạn có muốn xóa thông tin SV không?').waitFor();
    await click(page, 'Không');
    assert.equal((await data(page)).length, 2);
    await click(page, 'Xóa');
    await click(page, 'Có');
    await text(page, 'Quản lý sinh viên').waitFor();
    assert.deepEqual(await data(page), edited);
    passed('Edit duplicate blocked; Cancel discards; Delete No retains and Yes removes from storage/list');
    await click(page, 'Thêm mới');
    await fill(page, 'Họ tên', 'Bản nháp chưa lưu');
    await click(page, 'Hủy');
    assert.deepEqual(await data(page), edited);
    passed('Cancel add never auto-saves');
    await page.evaluate((storageKey) => {
      window.originalSetItem = Storage.prototype.setItem;
      Storage.prototype.setItem = function (key, value) { if (key === storageKey) throw new Error('Simulated disk full'); return window.originalSetItem.call(this, key, value); };
    }, key);
    await click(page, 'Thêm mới');
    await fill(page, 'Họ tên', 'Ghi lỗi');
    await fill(page, 'MSSV', 'BAA220000');
    await fill(page, 'Email', 'error@example.com');
    await click(page, 'Lưu');
    await text(page, 'Không thể lưu dữ liệu. Thay đổi chưa được ghi. Vui lòng thử lại.').waitFor();
    assert.deepEqual(await data(page), edited);
    assert.equal(await text(page, 'Đã thêm sinh viên.').count(), 0);
    await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
    await click(page, 'Lưu');
    await text(page, 'Chi tiết sinh viên').waitFor();
    assert.equal((await data(page)).length, 2);
    passed('Write failure leaves old data/UI unchanged; retry succeeds');
    const beforeFailedChanges = await data(page);
    await page.evaluate((storageKey) => {
      Storage.prototype.setItem = function (key, value) { if (key === storageKey) throw new Error('Simulated disk full'); return window.originalSetItem.call(this, key, value); };
    }, key);
    await click(page, 'Sửa');
    await fill(page, 'Họ tên', 'Thay đổi không ghi được');
    await click(page, 'Lưu');
    await click(page, 'Có');
    await text(page, 'Không thể lưu dữ liệu. Thay đổi chưa được ghi. Vui lòng thử lại.').waitFor();
    assert.deepEqual(await data(page), beforeFailedChanges);
    await click(page, 'Hủy');
    await text(page, 'Ghi lỗi').waitFor();
    await click(page, 'Xóa');
    await click(page, 'Có');
    await text(page, 'Không thể lưu dữ liệu. Thay đổi chưa được ghi. Vui lòng thử lại.').waitFor();
    assert.deepEqual(await data(page), beforeFailedChanges);
    await text(page, 'Chi tiết sinh viên').waitFor();
    await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
    passed('Edit/delete write failures keep the original record and remain on the appropriate screen');
    await click(page, 'Quay lại');
    await page.screenshot({ path: path.join(output, 'list-vi.png') });
    for (const width of [320, 375, 768, 1024, 1440, 1920]) {
      await page.setViewportSize({ width, height: 812 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, `List overflow at ${width}`);
    }
    await click(page, 'Thêm mới');
    await page.setViewportSize({ width: 320, height: 568 });
    await page.screenshot({ path: path.join(output, 'form-320.png') });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await click(page, 'Hủy');
    assert.deepEqual(errors, []);
    passed('Mobile 320/375 through desktop 1920 have no horizontal overflow or runtime errors');
    await context.close();

    const english = await browser.newContext({ locale: 'en-US', viewport: { width: 375, height: 812 } });
    const englishPage = await english.newPage();
    await englishPage.goto(url);
    await text(englishPage, 'Student Manager').waitFor();
    await click(englishPage, 'Add new');
    await click(englishPage, 'Save');
    await text(englishPage, 'Please enter a full name.').waitFor();
    await fill(englishPage, 'Full name', 'English unchanged');
    await fill(englishPage, 'Student ID', 'BAA220000');
    await fill(englishPage, 'Email', 'english@example.com');
    await click(englishPage, 'Save');
    await text(englishPage, 'Student details').waitFor();
    await click(englishPage, 'Edit');
    await click(englishPage, 'Save');
    await text(englishPage, 'Do you want to update this student’s information?').waitFor();
    await click(englishPage, 'No');
    await click(englishPage, 'Cancel');
    await click(englishPage, 'Delete');
    await text(englishPage, 'Do you want to delete this student’s information?').waitFor();
    await click(englishPage, 'No');
    await click(englishPage, 'Back');
    await englishPage.screenshot({ path: path.join(output, 'list-en.png') });
    passed('English labels, errors, edit/delete dialogs and user data');
    await englishPage.evaluate(() => {
      Object.defineProperty(navigator, 'languages', { configurable: true, value: ['vi-VN'] });
      Object.defineProperty(navigator, 'language', { configurable: true, value: 'vi-VN' });
      Object.defineProperty(document, 'hidden', { configurable: true, value: true });
      document.dispatchEvent(new Event('visibilitychange'));
      Object.defineProperty(document, 'hidden', { configurable: true, value: false });
      document.dispatchEvent(new Event('visibilitychange'));
    });
    await text(englishPage, 'Quản lý sinh viên').waitFor();
    assert.equal((await data(englishPage))[0].name, 'English unchanged');
    passed('Foreground re-reads device locale without translating user data');
    await english.close();

    const fallback = await browser.newContext({ locale: 'fr-FR' });
    const fallbackPage = await fallback.newPage();
    await fallbackPage.goto(url);
    await text(fallbackPage, 'Student Manager').waitFor();
    await text(fallbackPage, 'No students yet').waitFor();
    passed('A device language other than Vietnamese falls back to English');
    await fallback.close();

    const manyStudents = Array.from({ length: 60 }, (_, index) => ({
      id: `scroll-test-${index}`, name: index === 0 ? 'Sinh viên có họ tên rất dài để kiểm tra bố cục trên màn hình điện thoại nhỏ' : `Sinh viên ${index + 1}`,
      studentId: `BTT24${String(index).padStart(4, '0')}`,
      email: `${index === 0 ? 'longemail'.repeat(12) : `student${index}`}@example.com`, avatarUri: '',
    }));
    const many = await browser.newContext({ locale: 'vi-VN', viewport: { width: 320, height: 568 } });
    await many.addInitScript(({ storageKey, records }) => localStorage.setItem(storageKey, JSON.stringify(records)), { storageKey: key, records: manyStudents });
    const manyPage = await many.newPage();
    await manyPage.goto(url);
    await manyPage.getByRole('button', { name: `${manyStudents[0].name}, ${manyStudents[0].studentId}` }).waitFor();
    await manyPage.evaluate(() => {
      const scroller = [...document.querySelectorAll('div')].find((element) => element.clientHeight > 100 && element.scrollHeight > element.clientHeight && getComputedStyle(element).overflowY === 'auto');
      if (!scroller) throw new Error('No scrollable student list');
      scroller.scrollTop = scroller.scrollHeight;
    });
    await manyPage.getByRole('button', { name: 'Sinh viên 60, BTT240059' }).waitFor();
    await manyPage.goto(`${url}/student/${manyStudents[0].id}`);
    await text(manyPage, manyStudents[0].email).waitFor();
    assert.equal(await manyPage.evaluate((email) => {
      const element = [...document.querySelectorAll('div')].find((item) => item.childElementCount === 0 && item.textContent === email);
      if (!element) throw new Error('Email text not found');
      const range = document.createRange();
      range.selectNodeContents(element);
      return [...range.getClientRects()].some((rect) => rect.right > window.innerWidth + 1);
    }, manyStudents[0].email), false);
    await manyPage.screenshot({ path: path.join(output, 'long-detail-320.png') });
    passed('60 records scroll to the final item; direct detail reload and long text fit a 320px phone');
    await many.close();

    const corrupt = await browser.newContext({ locale: 'en-US' });
    await corrupt.addInitScript((storageKey) => localStorage.setItem(storageKey, '{corrupt'), key);
    const corruptPage = await corrupt.newPage();
    await corruptPage.goto(url);
    await text(corruptPage, 'Saved data could not be loaded. Please try again.').waitFor();
    assert.equal(await corruptPage.getByRole('button', { name: 'Add new', exact: true }).isDisabled(), true);
    assert.equal(await corruptPage.evaluate((storageKey) => localStorage.getItem(storageKey), key), '{corrupt');
    await corruptPage.evaluate((storageKey) => localStorage.setItem(storageKey, '[]'), key);
    await click(corruptPage, 'Retry');
    await text(corruptPage, 'No students yet').waitFor();
    passed('Failed initial read cannot overwrite saved data; Retry recovers');
    await corrupt.close();
    fs.writeFileSync(path.join(output, 'e2e-result.json'), JSON.stringify({ passed: checks, platform: 'Chromium web', nativeDeviceTested: false }, null, 2));
    console.log(`All ${checks} browser scenarios passed.`);
  } finally {
    await browser.close();
    await new Promise((resolve) => server.close(resolve));
  }
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
